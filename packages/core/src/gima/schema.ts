/**
 * The Gima (Sportpix) research server's database, copied from the real server's sqlite_master
 * (PRAGMA user_version = 1, considered final): participants, their watches, the data collection
 * requests and the watch's own tables. Every time is in MILLISECONDS (UTC). Activity rows are
 * 30-minute blocks (TIMESTAMP..TIMESTAMP_END) with the steps of that block, not cumulative.
 * ECG_MEASUREMENTS.ecg_data is a BLOB of signed 32-bit little-endian samples.
 */
export const GIMA_SCHEMA = `
CREATE TABLE IF NOT EXISTS participant (
    id INTEGER PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    birthday INTEGER,
    gender INTEGER,
    api_key_hash TEXT NOT NULL UNIQUE,
    fcm_token TEXT,
    created_at INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS device (
    id INTEGER PRIMARY KEY,
    participant_id INTEGER NOT NULL REFERENCES participant(id),
    name TEXT NOT NULL,
    identifier TEXT NOT NULL,
    hardware_id TEXT,
    firmware_version TEXT,
    last_measurement_at INTEGER,
    last_successful_upload_at INTEGER,
    UNIQUE (participant_id, identifier),
    UNIQUE (participant_id, id)
);

CREATE TABLE IF NOT EXISTS collection_request (
    request_code TEXT PRIMARY KEY,
    participant_id INTEGER NOT NULL REFERENCES participant(id),
    device_id INTEGER NOT NULL,
    client_request_id TEXT,
    table_name TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('AUTOMATIC', 'MANUAL', 'STATUS')),
    state TEXT NOT NULL CHECK (state IN ('PENDING', 'SENT', 'PROCESSING', 'FINISHED', 'ERROR')),
    start_ts INTEGER NOT NULL,
    end_ts INTEGER NOT NULL,
    created_at INTEGER NOT NULL,
    completed_at INTEGER,
    row_count INTEGER NOT NULL DEFAULT 0,
    min_timestamp INTEGER,
    max_timestamp INTEGER,
    error_message TEXT,
    UNIQUE (participant_id, client_request_id),
    FOREIGN KEY (participant_id, device_id) REFERENCES device(participant_id, id)
);

CREATE TABLE IF NOT EXISTS upload_batch (
    request_code TEXT NOT NULL REFERENCES collection_request(request_code),
    batch_index INTEGER NOT NULL,
    content_hash TEXT NOT NULL,
    is_final INTEGER NOT NULL,
    row_count INTEGER NOT NULL,
    PRIMARY KEY (request_code, batch_index)
) WITHOUT ROWID;

CREATE TABLE IF NOT EXISTS ECG_MEASUREMENTS (
    timestamp_string TEXT,
    start_measure_ms INTEGER NOT NULL,
    duration_ms INTEGER,
    sample_count INTEGER,
    heart INTEGER,
    dbp INTEGER,
    sbp INTEGER,
    hrv INTEGER,
    is_afib INTEGER,
    diagnose_type INTEGER,
    ai_heart INTEGER,
    DEVICE_ID INTEGER NOT NULL,
    USER_ID INTEGER NOT NULL,
    ecg_data BLOB NOT NULL,
    PRIMARY KEY (USER_ID, DEVICE_ID, start_measure_ms) ON CONFLICT REPLACE,
    FOREIGN KEY (USER_ID, DEVICE_ID) REFERENCES device(participant_id, id) ON DELETE CASCADE
) WITHOUT ROWID;

CREATE TABLE IF NOT EXISTS GIMA_ACTIVITY_SAMPLE (
    TIMESTAMP INTEGER NOT NULL,
    TIMESTAMP_END INTEGER NOT NULL,
    DEVICE_ID INTEGER NOT NULL,
    USER_ID INTEGER NOT NULL,
    STEPS INTEGER NOT NULL,
    DISTANCE_CM INTEGER NOT NULL,
    ACTIVE_CALORIES INTEGER NOT NULL,
    PRIMARY KEY (USER_ID, DEVICE_ID, TIMESTAMP) ON CONFLICT REPLACE,
    FOREIGN KEY (USER_ID, DEVICE_ID) REFERENCES device(participant_id, id) ON DELETE CASCADE
) WITHOUT ROWID;

CREATE TABLE IF NOT EXISTS GIMA_BLOOD_PRESSURE_SAMPLE (
    TIMESTAMP INTEGER NOT NULL,
    DEVICE_ID INTEGER NOT NULL,
    USER_ID INTEGER NOT NULL,
    BP_SYSTOLIC INTEGER NOT NULL,
    BP_DIASTOLIC INTEGER NOT NULL,
    PRIMARY KEY (USER_ID, DEVICE_ID, TIMESTAMP) ON CONFLICT REPLACE,
    FOREIGN KEY (USER_ID, DEVICE_ID) REFERENCES device(participant_id, id) ON DELETE CASCADE
) WITHOUT ROWID;

CREATE TABLE IF NOT EXISTS GIMA_BODY_TEMPERATURE_SAMPLE (
    TIMESTAMP INTEGER NOT NULL,
    DEVICE_ID INTEGER NOT NULL,
    USER_ID INTEGER NOT NULL,
    TEMPERATURE REAL NOT NULL,
    PRIMARY KEY (USER_ID, DEVICE_ID, TIMESTAMP) ON CONFLICT REPLACE,
    FOREIGN KEY (USER_ID, DEVICE_ID) REFERENCES device(participant_id, id) ON DELETE CASCADE
) WITHOUT ROWID;

CREATE TABLE IF NOT EXISTS GIMA_HEART_RATE_SAMPLE (
    TIMESTAMP INTEGER NOT NULL,
    DEVICE_ID INTEGER NOT NULL,
    USER_ID INTEGER NOT NULL,
    HEART_RATE INTEGER NOT NULL,
    PRIMARY KEY (USER_ID, DEVICE_ID, TIMESTAMP) ON CONFLICT REPLACE,
    FOREIGN KEY (USER_ID, DEVICE_ID) REFERENCES device(participant_id, id) ON DELETE CASCADE
) WITHOUT ROWID;

CREATE TABLE IF NOT EXISTS GIMA_HRV_VALUE_SAMPLE (
    TIMESTAMP INTEGER NOT NULL,
    DEVICE_ID INTEGER NOT NULL,
    USER_ID INTEGER NOT NULL,
    HRV INTEGER NOT NULL,
    CVRR INTEGER NOT NULL,
    PRIMARY KEY (USER_ID, DEVICE_ID, TIMESTAMP) ON CONFLICT REPLACE,
    FOREIGN KEY (USER_ID, DEVICE_ID) REFERENCES device(participant_id, id) ON DELETE CASCADE
) WITHOUT ROWID;

CREATE TABLE IF NOT EXISTS GIMA_RESPIRATORY_RATE_SAMPLE (
    TIMESTAMP INTEGER NOT NULL,
    DEVICE_ID INTEGER NOT NULL,
    USER_ID INTEGER NOT NULL,
    RESPIRATORY_RATE REAL NOT NULL,
    PRIMARY KEY (USER_ID, DEVICE_ID, TIMESTAMP) ON CONFLICT REPLACE,
    FOREIGN KEY (USER_ID, DEVICE_ID) REFERENCES device(participant_id, id) ON DELETE CASCADE
) WITHOUT ROWID;

CREATE TABLE IF NOT EXISTS GIMA_SLEEP_STAGE_SAMPLE (
    TIMESTAMP INTEGER NOT NULL,
    DEVICE_ID INTEGER NOT NULL,
    USER_ID INTEGER NOT NULL,
    DURATION_SEC INTEGER NOT NULL,
    STAGE INTEGER NOT NULL,
    PRIMARY KEY (USER_ID, DEVICE_ID, TIMESTAMP) ON CONFLICT REPLACE,
    FOREIGN KEY (USER_ID, DEVICE_ID) REFERENCES device(participant_id, id) ON DELETE CASCADE
) WITHOUT ROWID;

CREATE TABLE IF NOT EXISTS GIMA_SLEEP_STATS_SAMPLE (
    TIMESTAMP INTEGER NOT NULL,
    TIMESTAMP_END INTEGER NOT NULL,
    DEVICE_ID INTEGER NOT NULL,
    USER_ID INTEGER NOT NULL,
    RAPID_EYE_MOVEMENT_TOT INTEGER NOT NULL,
    DEEP_SLEEP_COUNT INTEGER NOT NULL,
    LIGHT_SLEEP_COUNT INTEGER NOT NULL,
    DEEP_SLEEP_TOT_MIN INTEGER NOT NULL,
    LIGHT_SLEEP_TOT_MIN INTEGER NOT NULL,
    PRIMARY KEY (USER_ID, DEVICE_ID, TIMESTAMP) ON CONFLICT REPLACE,
    FOREIGN KEY (USER_ID, DEVICE_ID) REFERENCES device(participant_id, id) ON DELETE CASCADE
) WITHOUT ROWID;

CREATE TABLE IF NOT EXISTS GIMA_SPO2_SAMPLE (
    TIMESTAMP INTEGER NOT NULL,
    DEVICE_ID INTEGER NOT NULL,
    USER_ID INTEGER NOT NULL,
    SPO2 INTEGER NOT NULL,
    PRIMARY KEY (USER_ID, DEVICE_ID, TIMESTAMP) ON CONFLICT REPLACE,
    FOREIGN KEY (USER_ID, DEVICE_ID) REFERENCES device(participant_id, id) ON DELETE CASCADE
) WITHOUT ROWID;

CREATE INDEX IF NOT EXISTS request_device ON collection_request(participant_id, device_id, created_at);

CREATE INDEX IF NOT EXISTS request_state ON collection_request(state, kind);
`;
