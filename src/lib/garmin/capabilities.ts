export type CapabilityProfile = "gadgetbridge" | "minimal";

export function ourCapabilities(profile: CapabilityProfile): Set<Capability> {
  return new Set(
    CAPABILITIES.filter((c) => (profile === "minimal" ? MINIMAL.has(c) : !GB_EXCLUDED.has(c))),
  );
}

export function capabilitiesToBinary(caps: Set<Capability>): Uint8Array {
  const out = new Uint8Array(Math.ceil(CAPABILITIES.length / 8));
  CAPABILITIES.forEach((c, i) => {
    if (caps.has(c)) out[i >> 3] |= 1 << (i & 7);
  });
  return out;
}

export function capabilitiesFromBinary(bytes: Uint8Array): Set<Capability> {
  const res = new Set<Capability>();
  for (let i = 0; i < bytes.length * 8; i++) {
    if (bytes[i >> 3] & (1 << (i & 7))) {
      const c = CAPABILITIES[i];
      if (c) res.add(c);
    }
  }
  return res;
}
