#!/usr/bin/env python3
"""
Generates src/lib/fit/profile.ts from Gadgetbridge's community FIT profile
(FitCodeGenerator/src/main/resources/fit_profile.json, AGPL-3.0).

Usage: python3 scripts/gen-fit-profile.py path/to/fit_profile.json > src/lib/fit/profile.ts
"""
import json
import sys

WANTED = {
    "FILE_ID", "FILE_CREATOR", "DEVICE_SETTINGS", "USER_PROFILE", "ZONES_TARGET", "SPORT", "SESSION", "LAP",
    "RECORD", "EVENT", "DEVICE_INFO", "ACTIVITY", "MONITORING", "MONITORING_INFO", "MONITORING_HR_DATA",
    "STRESS_LEVEL", "SPO2_DATA", "SLEEP_DATA_INFO", "SLEEP_DATA_RAW", "SLEEP_LEVEL", "RESPIRATION_RATE",
    "SLEEP_ASSESSMENT", "HRV_STATUS_SUMMARY", "HRV_VALUE", "SLEEP_RESTLESS_MOMENTS", "NAP_EVENT",
    "TIME_IN_ZONE", "HSA_BODY_BATTERY_DATA", "SKIN_TEMP_OVERNIGHT", "WEIGHT_SCALE", "TRAINING_LOAD",
    "PHYSIOLOGICAL_METRICS", "HRV", "BATTERY",
}


def main():
    src = json.load(open(sys.argv[1], encoding="utf-8"))
    msgs = [m for m in src["messages"] if m["name"] in WANTED]
    missing = WANTED - {m["name"] for m in msgs}
    print("/* eslint-disable */")
    print("// GENERATED by scripts/gen-fit-profile.py from Gadgetbridge's fit_profile.json (AGPL-3.0). Do not edit.")
    if missing:
        print("// not present in source profile: " + ", ".join(sorted(missing)))
    print("export interface FitFieldProfile { name: string; scale?: number; offset?: number; type?: string }")
    print("export interface FitMessageProfile { name: string; fields: Record<number, FitFieldProfile> }")
    print("export const FIT_PROFILE: Record<number, FitMessageProfile> = {")
    for m in sorted(msgs, key=lambda x: x["num"]):
        fields = []
        for f in m["fields"]:
            parts = [f'name: "{f["name"]}"']
            if f.get("scale") not in (None, 1):
                parts.append(f'scale: {f["scale"]}')
            if f.get("offset") not in (None, 0):
                parts.append(f'offset: {f["offset"]}')
            if f.get("type"):
                parts.append(f'type: "{f["type"]}"')
            fields.append(f'    {f["num"]}: {{ {", ".join(parts)} }},')
        print(f'  {m["num"]}: {{ name: "{m["name"].lower()}", fields: {{')
        print("\n".join(fields))
        print("  } },")
    print("};")
    enums = {e["name"]: e for e in src["enumerations"]}
    print("export const FIT_ENUMS: Record<string, Record<number, string>> = {")
    for name in ("SleepLevel", "HrvStatus", "Sport", "SubSport", "Event", "EventType"):
        e = enums.get(name)
        if not e:
            continue
        entries = ", ".join(f'{x["num"]}: "{x["name"]}"' for x in e["entries"])
        print(f"  {name}: {{ {entries} }},")
    print("};")


if __name__ == "__main__":
    main()
